"""
Swarm Data Models for Multi-Agent Consensus Architecture
"""
from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional


@dataclass
class FinOpsProposal:
    """
    Proposed cost reduction generated by the FinOps Agent.
    """
    resource_id: str
    current_spec: str
    proposed_spec: str
    current_monthly_cost: float
    proposed_monthly_cost: float
    estimated_savings_usd: float
    proposed_ram_gb: float
    proposed_vcpu: int
    rationale: str

    def __post_init__(self):
        if self.estimated_savings_usd < 0:
            raise ValueError(f"Savings cannot be negative: {self.estimated_savings_usd}")


@dataclass
class ArchReview:
    """
    Evaluation result from the Architecture & Reliability Agent.
    """
    is_approved: bool
    requires_counter_proposal: bool
    counter_proposed_spec: Optional[str] = None
    counter_proposed_cost: Optional[float] = None
    counter_proposed_ram_gb: Optional[float] = None
    counter_proposed_vcpu: Optional[int] = None
    peak_cpu_percent: float = 0.0
    peak_memory_used_gb: float = 0.0
    rationale: str = ""

    def __post_init__(self):
        if self.is_approved and self.requires_counter_proposal:
            raise ValueError("ArchReview cannot be both approved and require a counter-proposal")


@dataclass
class SecurityReview:
    """
    Evaluation result from the Security & Compliance Agent.
    """
    is_approved: bool
    violations: List[str] = field(default_factory=list)
    compliance_tags_valid: bool = True
    encryption_valid: bool = True
    rationale: str = ""


@dataclass
class SwarmConsensus:
    """
    Final agreed consensus decision output from the Swarm Orchestrator.
    """
    resource_id: str
    original_spec: str
    agreed_spec: str
    original_monthly_cost: float
    agreed_monthly_cost: float
    monthly_savings_usd: float
    is_approved: bool = True
    finops_proposal: Optional[FinOpsProposal] = None
    arch_review: Optional[ArchReview] = None
    security_review: Optional[SecurityReview] = None
    debate_trace: List[str] = field(default_factory=list)
    is_unanimous: bool = True
